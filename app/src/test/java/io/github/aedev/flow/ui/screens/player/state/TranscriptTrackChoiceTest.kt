package io.github.aedev.flow.ui.screens.player.state

import com.google.common.truth.Truth.assertThat
import io.github.aedev.flow.player.state.SubtitleOption
import io.github.aedev.flow.player.state.SubtitleOrigin
import org.junit.Test

class TranscriptTrackChoiceTest {
    private fun track(
        language: String,
        isAutoGenerated: Boolean = false,
        isTranslated: Boolean = false,
    ) = SubtitleOption(
        url = "https://example.test/$language?asr=$isAutoGenerated&tlang=$isTranslated",
        language = language,
        label = language,
        isAutoGenerated = isAutoGenerated,
        isTranslated = isTranslated,
    )

    private val arabic = track("ar")
    private val french = track("fr")
    private val german = track("de")
    private val englishAsr = track("en", isAutoGenerated = true)
    private val newsVideo = listOf(arabic, german, french, englishAsr)

    private fun pick(
        tracks: List<SubtitleOption>,
        pickedUrl: String? = null,
        showingUrl: String? = null,
        rememberedLanguage: String? = "none",
        subtitleLanguage: String? = "none",
        appLanguage: String? = null,
    ) = TranscriptTrackChoice.pick(tracks, pickedUrl, showingUrl, rememberedLanguage, subtitleLanguage, appLanguage)

    @Test
    fun `an English app opens the spoken English over authored tracks in other languages`() {
        assertThat(pick(newsVideo, appLanguage = "en-US")).isEqualTo(englishAsr)
    }

    @Test
    fun `the spoken language wins when nothing else matches`() {
        assertThat(pick(newsVideo, appLanguage = "ja-JP")).isEqualTo(englishAsr)
    }

    @Test
    fun `the remembered transcript language beats the app language`() {
        assertThat(pick(newsVideo, rememberedLanguage = "fr", appLanguage = "en-US")).isEqualTo(french)
    }

    @Test
    fun `the subtitle language beats the app language but not the remembered one`() {
        assertThat(pick(newsVideo, subtitleLanguage = "de", appLanguage = "en-US")).isEqualTo(german)
        assertThat(pick(newsVideo, rememberedLanguage = "fr", subtitleLanguage = "de")).isEqualTo(french)
    }

    @Test
    fun `an authored track beats an auto-generated one in the same language`() {
        val englishAuthored = track("en-GB")
        val tracks = listOf(englishAsr, englishAuthored, arabic)

        assertThat(pick(tracks, rememberedLanguage = "en")).isEqualTo(englishAuthored)
        assertThat(pick(tracks, appLanguage = "en-US")).isEqualTo(englishAuthored)
    }

    @Test
    fun `the subtitle that is showing wins over every language`() {
        assertThat(pick(newsVideo, showingUrl = german.url, rememberedLanguage = "fr", appLanguage = "en")).isEqualTo(german)
    }

    @Test
    fun `a pick made in the sheet wins over the showing subtitle`() {
        assertThat(pick(newsVideo, pickedUrl = arabic.url, showingUrl = german.url)).isEqualTo(arabic)
    }

    @Test
    fun `a pick or subtitle the video has no track for is ignored`() {
        val result = pick(newsVideo, pickedUrl = "https://example.test/gone", showingUrl = "file:///sdcard/a.srt", appLanguage = "en")

        assertThat(result).isEqualTo(englishAsr)
    }

    @Test
    fun `an auto-translation is not matched by language`() {
        val spanishTranslation = track("es", isAutoGenerated = true, isTranslated = true)
        val tracks = listOf(arabic, englishAsr, spanishTranslation)

        assertThat(pick(tracks, subtitleLanguage = "es")).isEqualTo(englishAsr)
    }

    @Test
    fun `without a match or an auto-generated track the first authored track opens`() {
        val spanishTranslation = track("es", isAutoGenerated = true, isTranslated = true)

        assertThat(pick(listOf(spanishTranslation, arabic, french), appLanguage = "ja")).isEqualTo(arabic)
    }

    @Test
    fun `with only a translation the first track opens`() {
        val spanishTranslation = track("es", isAutoGenerated = true, isTranslated = true)

        assertThat(pick(listOf(spanishTranslation), appLanguage = "ja")).isEqualTo(spanishTranslation)
    }

    @Test
    fun `tracks without a network URL are never read`() {
        val file =
            SubtitleOption(
                url = "file:///sdcard/en.srt",
                language = "en",
                label = "en",
                isAutoGenerated = false,
                origin = SubtitleOrigin.FILE,
            )

        assertThat(pick(listOf(file), appLanguage = "en")).isNull()
        assertThat(pick(listOf(file, arabic), appLanguage = "en")).isEqualTo(arabic)
    }

    @Test
    fun `a picked track is remembered by its base language`() {
        val englishUs = track("en-US")

        assertThat(TranscriptTrackChoice.languageToRemember(listOf(englishUs, arabic), englishUs.url)).isEqualTo("en")
        assertThat(TranscriptTrackChoice.languageToRemember(listOf(arabic), "https://example.test/gone")).isNull()
    }
}
