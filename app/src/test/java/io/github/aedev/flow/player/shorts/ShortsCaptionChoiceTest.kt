package io.github.aedev.flow.player.shorts

import com.google.common.truth.Truth.assertThat
import io.github.aedev.flow.player.state.SubtitleOption
import io.github.aedev.flow.player.subtitle.SubtitleAutoPolicy
import org.junit.Test

class ShortsCaptionChoiceTest {
    @Test
    fun `with nothing picked for Shorts, captions follow the video player's automatic captions`() {
        assertThat(ShortsCaptionChoice.policy(ShortsCaptionChoice.FOLLOW, autoEnable = true, preferredLanguage = "de"))
            .isEqualTo(SubtitleAutoPolicy(enabled = true, languageTag = "de"))
        assertThat(ShortsCaptionChoice.policy(ShortsCaptionChoice.FOLLOW, autoEnable = false, preferredLanguage = "de"))
            .isEqualTo(SubtitleAutoPolicy(enabled = false, languageTag = "de"))
    }

    @Test
    fun `turning captions off in Shorts keeps them off even when the video player turns them on`() {
        assertThat(ShortsCaptionChoice.policy(ShortsCaptionChoice.OFF, autoEnable = true, preferredLanguage = "de"))
            .isEqualTo(SubtitleAutoPolicy.OFF)
    }

    @Test
    fun `a language picked in Shorts turns captions on in it for the next reels`() {
        assertThat(ShortsCaptionChoice.policy("es", autoEnable = false, preferredLanguage = "de"))
            .isEqualTo(SubtitleAutoPolicy(enabled = true, languageTag = "es"))
    }

    @Test
    fun `picking a track stores its language, and picking off stores off`() {
        val spanish = SubtitleOption(url = "u", language = "es", label = "Spanish", isAutoGenerated = true)

        assertThat(ShortsCaptionChoice.stored(spanish)).isEqualTo("es")
        assertThat(ShortsCaptionChoice.stored(null)).isEqualTo(ShortsCaptionChoice.OFF)
        assertThat(ShortsCaptionChoice.stored(spanish.copy(language = ""))).isEqualTo(ShortsCaptionChoice.FOLLOW)
    }
}
