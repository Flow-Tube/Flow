package io.github.aedev.flow.player.stream

import io.github.aedev.flow.player.stream.model.AudioStream
import io.github.aedev.flow.player.stream.model.AudioTrackType
import io.github.aedev.flow.player.stream.model.MediaFormat
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test

private fun audioStream(
    trackId: String?,
    trackName: String? = null,
    bitrate: Int = 131_000,
    trackType: AudioTrackType? =
        trackId?.let {
            if (it.endsWith(".4")) AudioTrackType.ORIGINAL else AudioTrackType.DUBBED
        },
): AudioStream =
    AudioStream(
        id = trackId ?: "140",
        content = "https://example.invalid/${trackId ?: "default"}-$bitrate",
        format = MediaFormat.M4A,
        itagItem = null,
        averageBitrate = bitrate,
        audioTrackId = trackId,
        audioTrackName = trackName,
        audioTrackType = trackType,
    )

class StreamProcessorTest {
    @Test
    fun `a vtt copy of a track wins over another format of it`() {
        fun caption(format: CaptionFormat) =
            ResolvedCaption("en", isAutoGenerated = false, url = "https://yt/timedtext?lang=en&fmt=${format.name}", format = format)

        val processed = StreamProcessor.processCaptions(listOf(caption(CaptionFormat.TTML), caption(CaptionFormat.VTT)))

        assertEquals(CaptionFormat.VTT, processed.single().format)
    }

    @Test
    fun `two subtitle files in one language stay two tracks`() {
        fun file(name: String) =
            ResolvedCaption(
                "en",
                isAutoGenerated = false,
                url = "content://media/$name",
                format = CaptionFormat.SRT,
                label = name,
                source = CaptionSource.SIDECAR,
            )

        val processed = StreamProcessor.processCaptions(listOf(file("Movie.srt"), file("Movie.en.srt")))

        assertEquals(listOf("Movie.en.srt", "Movie.srt"), processed.map { it.label })
    }

    @Test
    fun `a file names its own track and an online track is named by its language`() {
        val options =
            StreamProcessor.toSubtitleOptions(
                listOf(
                    ResolvedCaption(
                        "",
                        isAutoGenerated = false,
                        url = "content://a",
                        format = CaptionFormat.SSA,
                        label = "Signs",
                        source = CaptionSource.SIDECAR,
                    ),
                    ResolvedCaption("xx-unknown", isAutoGenerated = true, url = "https://yt/x&tlang=xx", format = CaptionFormat.VTT),
                ),
            )

        assertEquals("Signs", options[0].label)
        assertTrue(options[1].isTranslated)
        assertTrue(options[1].isAutoGenerated)
    }

    @Test
    fun `different language tracks with the same role suffix remain distinct`() {
        val english = StreamProcessor.audioTrackGroupingKey("en.4", null, null, null)
        val spanish = StreamProcessor.audioTrackGroupingKey("es.4", null, null, null)

        assertNotEquals(english, spanish)
    }

    @Test
    fun `audio track ids retain their language instead of the shared role suffix`() {
        assertEquals("en", StreamProcessor.audioTrackLanguageTag("en.4"))
        assertEquals("es-US", StreamProcessor.audioTrackLanguageTag("es-US.4"))
        assertNotEquals(
            StreamProcessor.audioTrackLanguageTag("en.4"),
            StreamProcessor.audioTrackLanguageTag("es.4"),
        )
    }

    @Test
    fun `newpipe alternate audio track ids expose their language`() {
        assertEquals("hi", StreamProcessor.audioTrackLanguageTag("A_hi"))
        assertEquals("pt-BR", StreamProcessor.audioTrackLanguageTag("pt_BR"))
    }

    @Test
    fun `every dubbed track survives processing as its own row`() {
        val streams =
            listOf(
                audioStream("en.4", "English original"),
                audioStream("en.4", "English original", bitrate = 50_000),
                audioStream("ar.3", "Arabic"),
                audioStream("es.3", "Spanish"),
                audioStream("zh-Hans.3", "Chinese (Simplified)"),
            )

        val processed = StreamProcessor.processAudioStreams(streams)

        assertEquals(4, processed.size)
        // Alternate bitrates of one track collapse; the best is kept.
        assertEquals(131_000, processed.single { it.audioTrackId == "en.4" }.averageBitrate)
    }

    @Test
    fun `untagged audio is dropped once named tracks are present`() {
        val processed =
            StreamProcessor.processAudioStreams(
                listOf(
                    audioStream(null),
                    audioStream("en.4", "English original"),
                    audioStream("ar.3", "Arabic"),
                ),
            )

        assertEquals(2, processed.size)
        assertTrue(processed.all { it.audioTrackId != null })
    }

    @Test
    fun `untagged audio is kept when it is all we have`() {
        val processed = StreamProcessor.processAudioStreams(listOf(audioStream(null)))

        assertEquals(1, processed.size)
    }

    @Test
    fun `selected track index is resolved by identity not instance`() {
        val tracks =
            StreamProcessor.processAudioStreams(
                listOf(
                    audioStream("en.4", "English original"),
                    audioStream("ar.3", "Arabic"),
                    audioStream("es.3", "Spanish"),
                ),
            )
        // A distinct instance of the same logical track, as produced by the selection pass.
        val playing = audioStream("ar.3", "Arabic", bitrate = 50_000)

        val index = StreamProcessor.indexOfAudioTrack(tracks, playing)

        assertEquals("ar.3", tracks[index].audioTrackId)
    }

    @Test
    fun `only non original tracks override the default audio`() {
        assertTrue(StreamProcessor.overridesDefaultAudioTrack(audioStream("ar.3", "Arabic")))
        assertFalse(
            StreamProcessor.overridesDefaultAudioTrack(audioStream("en.4", "English original")),
        )
        assertFalse(StreamProcessor.overridesDefaultAudioTrack(null))
        assertFalse(StreamProcessor.overridesDefaultAudioTrack(audioStream(null, trackType = null)))
    }

    @Test
    fun `cast audio follows the playing track, not the first dub at the same bitrate`() {
        val raw =
            listOf(
                audioStream("ar.3", "Arabic"),
                audioStream("en.4", "English original"),
                audioStream("es.3", "Spanish"),
                audioStream("es.3", "Spanish", bitrate = 50_000),
            )

        assertEquals(listOf("es.3", "es.3"), StreamProcessor.streamsOfTrack(raw, audioStream("es.3", "Spanish")).map { it.audioTrackId })
        assertEquals(listOf("en.4"), StreamProcessor.streamsOfTrack(raw, null).map { it.audioTrackId })
        assertEquals(listOf("en.4"), StreamProcessor.streamsOfTrack(raw, audioStream("fr.3", "French")).map { it.audioTrackId })
    }

    @Test
    fun `cast audio without track identity is passed through`() {
        val raw = listOf(audioStream(null), audioStream(null, bitrate = 50_000))

        assertEquals(raw, StreamProcessor.streamsOfTrack(raw, null))
    }
}
