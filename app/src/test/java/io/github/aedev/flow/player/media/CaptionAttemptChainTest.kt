package io.github.aedev.flow.player.media

import androidx.media3.datasource.DataSource
import com.google.common.truth.Truth.assertThat
import io.github.aedev.flow.player.stream.CaptionFormat
import io.github.aedev.flow.player.stream.CaptionSource
import io.github.aedev.flow.player.stream.ResolvedCaption
import org.junit.Assert.assertThrows
import org.junit.Test
import java.io.IOException

class CaptionAttemptChainTest {
    private class Status(
        val code: Int?,
    ) : IOException("status $code")

    private val opened = mutableListOf<String>()

    private fun chain(vararg attempts: String) = CaptionAttemptChain(attempts.toList(), statusOf = { (it as? Status)?.code })

    private fun answering(vararg codes: Pair<String, Int?>): (String) -> String {
        val byAttempt = codes.toMap()
        return { attempt ->
            opened += attempt
            if (byAttempt.containsKey(attempt)) throw Status(byAttempt[attempt])
            attempt
        }
    }

    @Test
    fun `nothing extra is requested when the first load works`() {
        val result = chain("gemini", "classic", "okhttp").open(answering())

        assertThat(result).isEqualTo("gemini")
        assertThat(opened).containsExactly("gemini")
    }

    @Test
    fun `a refusal moves on to the next attempt once`() {
        val chain = chain("gemini", "classic", "okhttp")

        val result = chain.open(answering("gemini" to 403))

        assertThat(result).isEqualTo("classic")
        assertThat(opened).containsExactly("gemini", "classic").inOrder()
    }

    @Test
    fun `a refused attempt is never tried again for the track`() {
        val chain = chain("gemini", "classic", "okhttp")
        chain.open(answering("gemini" to 404))
        opened.clear()

        chain.open(answering())

        assertThat(opened).containsExactly("classic")
    }

    @Test
    fun `errors a retry can fix stay with the retry policy`() {
        listOf(429, 503, null).forEach { code ->
            opened.clear()
            assertThrows(Status::class.java) { chain("gemini", "classic").open(answering("gemini" to code)) }
            assertThat(opened).containsExactly("gemini")
        }
    }

    @Test
    fun `when every attempt is refused each is tried once and the last refusal is reported`() {
        val error =
            assertThrows(Status::class.java) {
                chain("gemini", "classic", "okhttp").open(
                    answering(
                        "gemini" to 403,
                        "classic" to 403,
                        "okhttp" to 404,
                    ),
                )
            }

        assertThat(error.code).isEqualTo(404)
        assertThat(opened).containsExactly("gemini", "classic", "okhttp").inOrder()
    }

    private val primary = DataSource.Factory { error("not opened in this test") }
    private val other = DataSource.Factory { error("not opened in this test") }

    private fun caption(
        url: String,
        auto: Boolean = true,
        source: CaptionSource = CaptionSource.YOUTUBE,
    ) = ResolvedCaption(languageTag = "en", isAutoGenerated = auto, url = url, format = CaptionFormat.VTT, source = source)

    private val gemini = "https://www.youtube.com/api/timedtext?v=x&signature=S&kind=asr&lang=en&variant=gemini&fmt=vtt"

    @Test
    fun `only native auto tracks get a fallback`() {
        assertThat(captionDataSourceFactory(caption(gemini), primary, other, "en")).isNotSameInstanceAs(primary)
        assertThat(captionDataSourceFactory(caption(gemini), primary, null, "en")).isNotSameInstanceAs(primary)
        assertThat(captionDataSourceFactory(caption("$gemini&tlang=pt"), primary, other, "pt")).isSameInstanceAs(primary)
        assertThat(captionDataSourceFactory(caption(gemini, auto = false), primary, other, "en")).isSameInstanceAs(primary)
        assertThat(captionDataSourceFactory(caption(gemini, source = CaptionSource.STORED), primary, other, "en")).isSameInstanceAs(primary)
    }

    @Test
    fun `a classic auto track with no other transport keeps its source`() {
        val classic = gemini.replace("&variant=gemini", "")

        assertThat(captionDataSourceFactory(caption(classic), primary, null, "en")).isSameInstanceAs(primary)
        assertThat(captionDataSourceFactory(caption(classic), primary, other, "en")).isNotSameInstanceAs(primary)
    }
}
