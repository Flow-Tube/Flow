package io.github.aedev.flow.player.stream

import android.util.Log
import io.github.aedev.flow.innertube.models.response.PlayerResponse
import java.util.Locale

object CaptionTrackResolver {
    private const val TAG = "CaptionTrackResolver"

    /** Marks a track produced by YouTube's machine translation of another caption track. */
    const val TRANSLATED_PARAM = "tlang"

    const val NO_PREFERRED_LANGUAGE = "none"

    private const val ASR_KIND = "asr"

    /** Marks the speech track YouTube made for an auto-dubbed audio track rather than for the video. */
    private const val DUB_TRANSCRIPT_PARAM = "variant=timing-optimized"

    /**
     * @param format timedtext format requested for authored tracks. Defaults to
     *   [CaptionFormat.SRV3], YouTube's own styled/positioned caption XML, decoded by
     *   [io.github.aedev.flow.player.renderer.subtitle.Srv3SubtitleParser]. Callers that need the
     *   plain-text `vtt` conversion (offline downloads validate and store the raw response body)
     *   pass [CaptionFormat.VTT] explicitly. Auto-generated (ASR) tracks always stay on `vtt`
     *   regardless: their srv3 form is a roll-up stream of word-timed segments, which the rolling
     *   caption renderer does not reconstruct.
     * @param translateTo a BCP-47 tag to machine-translate into when the video carries no track in
     *   that language. Only one is produced: the response offers up to 156 translation languages,
     *   and materialising them all would bury the authored tracks in the picker.
     */
    fun resolve(
        playerResponse: PlayerResponse,
        format: CaptionFormat = CaptionFormat.SRV3,
        translateTo: String? = null,
    ): List<ResolvedCaption> = resolveTracklist(playerResponse.captions?.playerCaptionsTracklistRenderer, format, translateTo)

    fun resolveTracklist(
        renderer: PlayerResponse.Captions.PlayerCaptionsTracklistRenderer?,
        format: CaptionFormat = CaptionFormat.SRV3,
        translateTo: String? = null,
    ): List<ResolvedCaption> {
        if (renderer == null) return emptyList()
        // Indexed before filtering: audioTracks point at positions in the full list.
        val indexed =
            renderer.captionTracks
                .orEmpty()
                .withIndex()
                .filter { !it.value.baseUrl.isNullOrBlank() && !it.value.languageCode.isNullOrBlank() }
        if (indexed.isEmpty()) return emptyList()
        val tracks = indexed.map { it.value }

        val result =
            indexed.map { (index, track) ->
                val autoGenerated = track.kind == ASR_KIND
                val trackFormat = if (autoGenerated) CaptionFormat.VTT else format
                ResolvedCaption(
                    languageTag = track.languageCode!!,
                    isAutoGenerated = autoGenerated,
                    url = timedTextUrl(track.baseUrl!!, trackFormat),
                    format = trackFormat,
                    name = track.name?.text?.takeIf { it.isNotBlank() },
                    trackId = track.identity(),
                    audioLinks = audioLinks(renderer, index),
                )
            }

        val translated = translatedTrack(renderer, tracks, result, translateTo, format)
        Log.d(TAG, "Resolved ${result.size} caption tracks from InnerTube captions (translated=${translated != null})")
        return if (translated == null) result else result + translated
    }

    private fun translatedTrack(
        renderer: PlayerResponse.Captions.PlayerCaptionsTracklistRenderer,
        tracks: List<PlayerResponse.Captions.CaptionTrack>,
        resolved: List<ResolvedCaption>,
        translateTo: String?,
        format: CaptionFormat,
    ): ResolvedCaption? {
        val wanted = translateTo?.takeIf { it.isNotBlank() && it != NO_PREFERRED_LANGUAGE } ?: return null
        val offered =
            renderer.translationLanguages
                ?.mapNotNull { it.languageCode }
                ?.firstOrNull { baseLanguage(it) == baseLanguage(wanted) }
                ?: return null
        val alreadyCovered =
            bestMatch(
                candidates = resolved,
                languageTag = offered,
                tagOf = { it.languageTag },
                isAutoGenerated = { it.isAutoGenerated },
            ) != null
        if (alreadyCovered) return null

        // The speech track in vtt, as YouTube's apps and NewTube ask for a translation (#1369). An
        // auto-dub's transcript is passed over: translating it would translate the dub.
        val translatable = tracks.filter { it.isTranslatable == true }
        val source =
            translatable.firstOrNull { it.kind == ASR_KIND && !it.isDubTranscript() }
                ?: translatable.firstOrNull { it.kind != ASR_KIND }
                ?: translatable.firstOrNull()
                ?: return null
        return ResolvedCaption(
            languageTag = offered,
            isAutoGenerated = true,
            url = "${timedTextUrl(source.baseUrl!!, CaptionFormat.VTT)}&$TRANSLATED_PARAM=$offered",
            format = CaptionFormat.VTT,
        )
    }

    private fun audioLinks(
        renderer: PlayerResponse.Captions.PlayerCaptionsTracklistRenderer,
        captionIndex: Int,
    ): List<CaptionAudioLink> =
        renderer.audioTracks.orEmpty().withIndex().mapNotNull { (audioIndex, audio) ->
            if (audio.captionTrackIndices?.contains(captionIndex) != true) return@mapNotNull null
            CaptionAudioLink(
                audioTrackId = audio.audioTrackId?.takeIf { it.isNotBlank() },
                isDefaultAudioTrack = audioIndex == renderer.defaultAudioTrackIndex,
                isDefaultCaption = audio.hasDefaultTrack != false && audio.defaultCaptionTrackIndex == captionIndex,
                initialState = CaptionsInitialState.parse(audio.captionsInitialState),
            )
        }

    /** The vssId, else the language and the creator's track name, which a vssId is built from. */
    private fun PlayerResponse.Captions.CaptionTrack.identity(): String? =
        vssId?.takeIf { it.isNotBlank() }
            ?: trackName?.takeIf { it.isNotBlank() }?.let { "$languageCode.$it" }

    private fun PlayerResponse.Captions.CaptionTrack.isDubTranscript(): Boolean = baseUrl?.contains(DUB_TRANSCRIPT_PARAM) == true

    private fun timedTextUrl(
        baseUrl: String,
        format: CaptionFormat,
    ): String {
        val separatorIndex = baseUrl.indexOf('?')
        val path = if (separatorIndex >= 0) baseUrl.substring(0, separatorIndex) else baseUrl
        val query = if (separatorIndex >= 0) baseUrl.substring(separatorIndex + 1) else ""

        val retained =
            query
                .split('&')
                .filter { it.isNotEmpty() && !it.isParam("fmt") && !it.isParam(TRANSLATED_PARAM) }
                .toMutableList()

        retained.add("fmt=${format.fmtQueryValue ?: CaptionFormat.SRV3.fmtQueryValue}")

        return "$path?${retained.joinToString("&")}"
    }

    private fun String.isParam(name: String): Boolean = startsWith("$name=", ignoreCase = true) || equals(name, ignoreCase = true)

    fun <T> bestMatch(
        candidates: List<T>,
        languageTag: String?,
        tagOf: (T) -> String?,
        isAutoGenerated: (T) -> Boolean,
    ): T? {
        val wanted = languageTag?.takeIf { it.isNotBlank() && it != NO_PREFERRED_LANGUAGE } ?: return null
        val wantedBase = baseLanguage(wanted)
        val ranked =
            candidates
                .filter { baseLanguage(tagOf(it).orEmpty()) == wantedBase }
                .sortedWith(
                    compareBy<T> { !tagOf(it).equals(wanted, ignoreCase = true) }
                        .thenBy { isAutoGenerated(it) },
                )
        return ranked.firstOrNull()
    }

    fun baseLanguage(tag: String): String =
        tag
            .substringBefore('-')
            .substringBefore('_')
            .lowercase(Locale.ROOT)
}
