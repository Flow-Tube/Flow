package io.github.aedev.flow.player.shorts

import android.net.Uri
import android.util.Log
import androidx.annotation.OptIn
import androidx.media3.common.C
import androidx.media3.common.MediaItem
import androidx.media3.common.util.UnstableApi
import androidx.media3.datasource.DataSource
import androidx.media3.exoplayer.ExoPlayer
import androidx.media3.exoplayer.dash.DashMediaSource
import androidx.media3.exoplayer.source.MediaSource
import androidx.media3.exoplayer.source.MergingMediaSource
import androidx.media3.exoplayer.source.ProgressiveMediaSource
import androidx.media3.exoplayer.source.SingleSampleMediaSource
import io.github.aedev.flow.player.media.MediaLoader
import io.github.aedev.flow.player.renderer.subtitle.Srv3SubtitleParser
import io.github.aedev.flow.player.resolver.MediaSourceBuilder
import io.github.aedev.flow.player.stream.ResolvedCaption

/**
 * Loads a reel into a pooled player: separate video and audio merged, or one muxed stream, with
 * the reel's caption tracks beside them. A caption track loads only once text is switched on for
 * its player, so a reel shown without captions never fetches one.
 */
@OptIn(UnstableApi::class)
internal object ShortsMediaSources {
    private const val TAG = "ShortsPlayerPool"

    init {
        Srv3SubtitleParser.registerTrackType()
    }

    fun load(
        player: ExoPlayer,
        factory: DataSource.Factory,
        streams: ShortsSlotStreams,
    ) {
        val videoUrl = streams.videoUrl
        val audioUrl = streams.audioUrl
        val media =
            if (audioUrl != null && audioUrl != videoUrl) {
                val videoSource =
                    streams.adaptiveManifest?.let { DashMediaSource.Factory(factory).createMediaSource(it, MediaItem.fromUri(videoUrl)) }
                        ?: sourceFor(factory, videoUrl, streams.videoManifest)
                listOf(videoSource, sourceFor(factory, audioUrl, streams.audioManifest))
            } else {
                listOf(sourceFor(factory, videoUrl, streams.videoManifest))
            }
        // Through the same factory as the streams: a looping reel asks for its caption track again on every loop.
        val sources = media + streams.captions.mapIndexed { index, caption -> captionSource(factory, index, caption) }
        player.setMediaSource(sources.singleOrNull() ?: MergingMediaSource(true, true, *sources.toTypedArray()))
        player.prepare()
    }

    private fun sourceFor(
        factory: DataSource.Factory,
        url: String,
        dashManifest: String?,
    ): MediaSource {
        if (dashManifest != null) {
            runCatching {
                return MediaSourceBuilder.buildDashSource(factory, dashManifest, Uri.parse(url))
            }.onFailure { Log.w(TAG, "Generated DASH manifest rejected, falling back to progressive: ${it.message}") }
        }
        return ProgressiveMediaSource
            .Factory(factory)
            .createMediaSource(MediaItem.fromUri(url))
    }

    /** Under the same track id as the video player's, so [io.github.aedev.flow.player.subtitle.SubtitleTracks] finds it. */
    private fun captionSource(
        factory: DataSource.Factory,
        index: Int,
        caption: ResolvedCaption,
    ): MediaSource {
        val language = caption.languageTag.takeIf { it.isNotBlank() }
        val config =
            MediaItem.SubtitleConfiguration
                .Builder(Uri.parse(caption.url))
                .setMimeType(caption.format.mimeType)
                .setLanguage(language)
                .setLabel(caption.label ?: language)
                .setRoleFlags(
                    if (caption.isAutoGenerated) C.ROLE_FLAG_SUBTITLE or C.ROLE_FLAG_TRANSCRIBES_DIALOG else C.ROLE_FLAG_SUBTITLE,
                ).setId(MediaLoader.subtitleTrackId(index))
                .build()
        return SingleSampleMediaSource
            .Factory(factory)
            // A caption that fails to load must not stop the reel.
            .setTreatLoadErrorsAsEndOfStream(true)
            .createMediaSource(config, C.TIME_UNSET)
    }
}
