package io.github.aedev.flow.player.media

import android.net.Uri
import android.util.Log
import androidx.media3.common.util.UnstableApi
import androidx.media3.datasource.DataSource
import androidx.media3.datasource.DataSpec
import androidx.media3.datasource.TransferListener
import io.github.aedev.flow.player.stream.CaptionSource
import io.github.aedev.flow.player.stream.CaptionUrlFallback
import io.github.aedev.flow.player.stream.ResolvedCaption
import java.io.IOException

private const val TAG = "MediaLoader"

/**
 * Walks a caption track's fetch attempts in order, moving on only when one is refused outright.
 * A refused attempt is never tried again for this track, and anything else (a timeout, a 429, a
 * 5xx) is left to the subtitle retry policy.
 */
internal class CaptionAttemptChain<T>(
    private val attempts: List<T>,
    private val statusOf: (IOException) -> Int?,
    private val onRefused: (refused: T, status: Int?) -> Unit = { _, _ -> },
) {
    private var next = 0

    @Synchronized
    fun <R> open(tryOpen: (T) -> R): R {
        while (true) {
            val index = next
            try {
                return tryOpen(attempts[index])
            } catch (e: IOException) {
                val status = statusOf(e)
                if (!CaptionUrlFallback.isRefusal(status) || index == attempts.lastIndex) throw e
                onRefused(attempts[index], status)
                next = index + 1
            }
        }
    }
}

internal data class CaptionAttempt(
    val factory: DataSource.Factory,
    val url: String,
)

/**
 * The source a YouTube auto caption track is fetched through: its own URL, then the classic auto
 * track ([CaptionUrlFallback]), then the same URL over [otherTransport]. Authored, translated and
 * local tracks keep [primary] as is.
 */
@UnstableApi
internal fun captionDataSourceFactory(
    caption: ResolvedCaption,
    primary: DataSource.Factory,
    otherTransport: DataSource.Factory?,
    label: String,
): DataSource.Factory {
    if (caption.source != CaptionSource.YOUTUBE || !caption.isAutoGenerated || caption.isTranslated) return primary
    val attempts =
        buildList {
            add(CaptionAttempt(primary, caption.url))
            CaptionUrlFallback.alternateFor(caption.url)?.let { add(CaptionAttempt(primary, it)) }
            otherTransport?.let { add(CaptionAttempt(it, caption.url)) }
        }
    if (attempts.size == 1) return primary
    val chain =
        CaptionAttemptChain(attempts, SubtitleLoadDiagnostics::statusOf) { _, status ->
            Log.w(TAG, "Subtitle '$label' refused (status=$status), trying the next source")
        }
    return DataSource.Factory { FallbackDataSource(chain) }
}

@UnstableApi
private class FallbackDataSource(
    private val chain: CaptionAttemptChain<CaptionAttempt>,
) : DataSource {
    private val listeners = mutableListOf<TransferListener>()
    private var current: DataSource? = null

    override fun addTransferListener(transferListener: TransferListener) {
        listeners += transferListener
    }

    override fun open(dataSpec: DataSpec): Long =
        chain.open { attempt ->
            val source = attempt.factory.createDataSource()
            listeners.forEach(source::addTransferListener)
            try {
                source.open(dataSpec.withUri(Uri.parse(attempt.url))).also { current = source }
            } catch (e: IOException) {
                runCatching { source.close() }
                throw e
            }
        }

    override fun read(
        buffer: ByteArray,
        offset: Int,
        length: Int,
    ): Int = checkNotNull(current).read(buffer, offset, length)

    override fun getUri(): Uri? = current?.uri

    override fun getResponseHeaders(): Map<String, List<String>> = current?.responseHeaders ?: emptyMap()

    override fun close() {
        try {
            current?.close()
        } finally {
            current = null
        }
    }
}
