import android.os.SystemClock
import android.util.Log
import io.github.aedev.flow.data.local.PlayerPreferences
import io.github.aedev.flow.data.shorts.ShortsDashManifest
import io.github.aedev.flow.data.shorts.selectShortAudioFormat
import io.github.aedev.flow.data.shorts.selectShortVideoFormat
import io.github.aedev.flow.player.stream.CaptionFormat
import io.github.aedev.flow.player.stream.CaptionTrackResolver
import io.github.aedev.flow.player.stream.InnerTubeVideoStreamExtractor
import io.github.aedev.flow.player.stream.InnerTubeVideoStreamExtractor.VideoExtractionResult
import io.github.aedev.flow.player.stream.ResolvedCaption
import io.github.aedev.flow.player.stream.StoryboardLevel
import io.github.aedev.flow.player.stream.StoryboardSpec
import io.github.aedev.flow.player.stream.durationMs
import io.github.aedev.flow.player.stream.playableAudioFormats
import io.github.aedev.flow.player.stream.playableVideoFormats
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeoutOrNull
import java.util.Locale
import javax.inject.Inject
import javax.inject.Singleton

/** Everything one preview plays: a single ≤480p video rep, one audio rep, and at most one caption track. */
internal data class FeedPreviewMedia(
    val videoId: String,
    val videoUrl: String,
    val videoDashManifest: String?,
    val audioUrl: String?,
    val audioDashManifest: String?,
    val durationMs: Long,
    val caption: ResolvedCaption?,
    val captionsByDefault: Boolean,
    val storyboard: List<StoryboardLevel>,
)

/**
 * Resolves a preview through the main player's own extraction ([InnerTubeVideoStreamExtractor],
 * whose coalescer a watch-page load joins), and keeps each result so a card selected again costs no
 * second `/player`, and a tap can hand the extraction to the watch page.
 */
@Singleton
internal class FeedPreviewStreams
    @Inject
    constructor(
        private val preferences: PlayerPreferences,
    ) {
        private class Held(
            val result: VideoExtractionResult,
            val atMs: Long,
        )

        private val held =
            object : LinkedHashMap<String, Held>(MAX_HELD, 0.75f, true) {
                override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, Held>?): Boolean = size > MAX_HELD
            }

        suspend fun resolve(videoId: String): FeedPreviewMedia? {
            val result = extraction(videoId) ?: return null
            return withContext(Dispatchers.Default) { assemble(videoId, result) }
        }

        private suspend fun assemble(
            videoId: String,
            result: VideoExtractionResult,
        ): FeedPreviewMedia? {
            if (result.isLive) return null
            val durationMs = result.durationMs()?.takeIf { it > 0L } ?: return null
            val video =
                selectShortVideoFormat(result.playableVideoFormats(), PREVIEW_HEIGHT, preferences.videoCodecPriority.first())
                    ?: return null
            val videoUrl = video.url ?: return null
            val audio = selectShortAudioFormat(result.playableAudioFormats(), preferences.preferredAudioLanguage.first())
            val captions = CaptionTrackResolver.resolve(result.playerResponse, CaptionFormat.VTT)
            val preferred =
                CaptionTrackResolver.bestMatch(captions, preferences.preferredSubtitleLanguage.first(), {
                    it.languageTag
                }, { it.isAutoGenerated })
            val caption =
                preferred
                    ?: CaptionTrackResolver.bestMatch(captions, Locale.getDefault().language, { it.languageTag }, { it.isAutoGenerated })
                    ?: captions.firstOrNull { !it.isTranslated }
            return FeedPreviewMedia(
                videoId = videoId,
                videoUrl = videoUrl,
                videoDashManifest = ShortsDashManifest.forVideo(video, videoUrl, durationMs),
                audioUrl = audio?.url,
                audioDashManifest = audio?.url?.let { ShortsDashManifest.forAudio(audio, it, durationMs) },
                durationMs = durationMs,
                caption = caption,
                captionsByDefault = preferred != null,
                storyboard =
                    StoryboardSpec.parse(
                        result.playerResponse.storyboards
                            ?.playerStoryboardSpecRenderer
                            ?.spec,
                        durationMs,
                    ),
            )
        }

        /**
         * Offers [videoId]'s extraction to the watch-page load that follows a tap, which takes it
         * instead of asking `/player` again. Only a recent one: an old preview's URLs are left to a
         * fresh extraction.
         */
        fun handOff(videoId: String) {
            val entry = synchronized(held) { held[videoId] } ?: return
            if (SystemClock.elapsedRealtime() - entry.atMs > HANDOFF_MAX_AGE_MS) return
            InnerTubeVideoStreamExtractor.handOffPromoted(videoId, entry.result)
        }

        private suspend fun extraction(videoId: String): VideoExtractionResult? {
            synchronized(held) { held[videoId] }
                ?.takeIf { SystemClock.elapsedRealtime() - it.atMs < REUSE_MAX_AGE_MS }
                ?.let { return it.result }
            val result =
                try {
                    withTimeoutOrNull(EXTRACT_TIMEOUT_MS) { InnerTubeVideoStreamExtractor.extract(videoId) }
                } catch (e: CancellationException) {
                    throw e
                } catch (e: Exception) {
                    Log.w(TAG, "Preview extraction failed for $videoId: ${e.javaClass.simpleName}")
                    null
                } ?: return null
            synchronized(held) { held[videoId] = Held(result, SystemClock.elapsedRealtime()) }
            return result
        }

        private companion object {
            const val TAG = "FeedPreviewStreams"
            const val PREVIEW_HEIGHT = 480
            const val MAX_HELD = 20
            const val EXTRACT_TIMEOUT_MS = 8_000L
            const val REUSE_MAX_AGE_MS = 30 * 60_000L
            const val HANDOFF_MAX_AGE_MS = 10 * 60_000L
        }
    }
