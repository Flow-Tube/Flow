package io.github.aedev.flow.player.stream

import android.util.Log
import io.github.aedev.flow.player.state.AudioTrackOption
import io.github.aedev.flow.player.state.SubtitleOption
import io.github.aedev.flow.player.state.SubtitleOrigin
import io.github.aedev.flow.player.stream.model.AudioStream
import io.github.aedev.flow.player.stream.model.AudioTrackType
import io.github.aedev.flow.player.stream.model.VideoStream
import java.util.Locale

/**
 * Manages stream data processing - deduplication, sorting, and conversion.
 */
object StreamProcessor {
    private const val TAG = "StreamProcessor"

    /** Grouping key for audio carrying no track identity at all. */
    internal const val UNTAGGED_TRACK_KEY = "default"

    private const val UNKNOWN_LANGUAGE = "Unknown"

    /**
     * Process video streams - deduplicate and sort by height descending.
     */
    fun processVideoStreams(streams: List<VideoStream>): List<VideoStream> =
        streams
            .distinctBy { it.content }
            .sortedWith(
                compareByDescending<VideoStream> { VideoCodecUtils.qualityHeightFromStream(it) }
                    .thenBy { VideoCodecUtils.playbackCodecRank(it) }
                    .thenByDescending { it.bitrate },
            ).also { Log.d(TAG, "Processed ${streams.size} video streams -> ${it.size} unique") }

    fun processAudioStreams(streams: List<AudioStream>): List<AudioStream> =
        streams
            .sortedByDescending { it.averageBitrate }
            .groupBy { stream -> extractTrackLanguageKey(stream) }
            .dropUntaggedGroupWhenTracksAreKnown()
            .map { (_, group) ->
                group.first()
            }.sortedBy { stream -> audioTrackDisplayName(stream).orEmpty() }
            .also { Log.d(TAG, "Processed ${streams.size} audio streams -> ${it.size} unique tracks") }

    /**
     * Once named tracks are present, the untagged bucket is the same audio arriving from a backend
     * that does not name tracks (the two extraction paths get merged). Keeping it would render an
     * unlabelled duplicate row beside the real ones.
     */
    private fun Map<String, List<AudioStream>>.dropUntaggedGroupWhenTracksAreKnown(): Map<String, List<AudioStream>> =
        if (size > 1) this - UNTAGGED_TRACK_KEY else this

    /**
     * One track per YouTube track id (else per language), kind and translation, ordered authored
     * first, then auto-generated, then translations. Files on the device are never merged: two of
     * them in one language are two different subtitles.
     */
    fun processCaptions(captions: List<ResolvedCaption>): List<ResolvedCaption> =
        captions
            .filter { it.url.isNotBlank() }
            .sortedBy { it.format != CaptionFormat.VTT }
            .distinctBy { caption ->
                when (caption.source) {
                    CaptionSource.SIDECAR, CaptionSource.PICKED -> caption.url
                    else -> "${caption.trackId ?: caption.languageTag}|${caption.isAutoGenerated}|${caption.isTranslated}"
                }
            }.sortedWith(
                compareBy<ResolvedCaption> { it.isTranslated }
                    .thenBy { it.isAutoGenerated }
                    .thenBy { captionLabel(it) },
            ).also { Log.d(TAG, "Processed ${captions.size} captions -> ${it.size} unique tracks") }

    /**
     * Index of [stream]'s logical track within [tracks], or 0 when it cannot be placed.
     *
     * Matched by track identity rather than instance: the playing stream is picked from the raw
     * list while [tracks] holds one representative per track, so the two are rarely the same
     * object and an instance lookup silently reports the wrong row as selected.
     */
    fun indexOfAudioTrack(
        tracks: List<AudioStream>,
        stream: AudioStream?,
    ): Int {
        if (stream == null) return 0
        val key = extractTrackLanguageKey(stream)
        return tracks.indexOfFirst { extractTrackLanguageKey(it) == key }.coerceAtLeast(0)
    }

    /**
     * The formats of [current]'s logical track, else of the original track, else [streams] as given.
     * Dubs share one itag and bitrate, so a pick by bitrate alone lands on an arbitrary language.
     */
    fun streamsOfTrack(
        streams: List<AudioStream>,
        current: AudioStream?,
    ): List<AudioStream> {
        if (current != null) {
            val key = extractTrackLanguageKey(current)
            streams.filter { extractTrackLanguageKey(it) == key }.takeIf { it.isNotEmpty() }?.let { return it }
        }
        return streams.filter { it.audioTrackType == AudioTrackType.ORIGINAL }.ifEmpty { streams }
    }

    /**
     * True when this stream is a track chosen over YouTube's default. Neither YouTube's own DASH
     * manifest nor a SABR session can serve such a choice — both carry only the default track — so
     * playback has to fall through to a manifest generated from this specific stream.
     */
    fun overridesDefaultAudioTrack(stream: AudioStream?): Boolean {
        val type = stream?.audioTrackType ?: return false
        return type != AudioTrackType.ORIGINAL
    }

    /** Derive a stable logical-track key while collapsing only alternate formats of that track. */
    private fun extractTrackLanguageKey(stream: AudioStream): String =
        audioTrackGroupingKey(
            trackId = stream.audioTrackId,
            trackName = stream.audioTrackName,
            languageTag = stream.audioLocale?.toLanguageTag(),
            trackType = stream.audioTrackType?.name,
        )

    /**
     * Derive a human-readable language display name from an AudioStream.
     * Priority: audioTrackName → audioLocale display language → parsed audioTrackId → fallback.
     */
    fun audioTrackDisplayName(stream: AudioStream): String? {
        stream.audioTrackName?.takeIf { it.isNotBlank() }?.let { return it }

        stream.audioLocale?.language?.takeIf { it.isNotBlank() }?.let { langCode ->
            localizedLanguageName(langCode)?.let { return it }
        }

        stream.audioTrackId?.let { trackId ->
            audioTrackLanguageTag(trackId)?.let { languageTag ->
                localizedLanguageName(languageTag)?.let { return it }
            }
            return trackId.replaceFirstChar { it.uppercase() }
        }

        return null
    }

    /**
     * Convert audio streams to UI options.
     */
    fun toAudioTrackOptions(streams: List<AudioStream>): List<AudioTrackOption> =
        streams.mapIndexed { index, stream ->
            AudioTrackOption(
                index = index,
                label = audioTrackDisplayName(stream).orEmpty(),
                language =
                    stream.audioLocale
                        ?.displayLanguage
                        ?.takeIf { it.isNotBlank() }
                        ?: "",
                bitrate = stream.averageBitrate.coerceAtLeast(0).toLong(),
            )
        }

    fun toSubtitleOptions(captions: List<ResolvedCaption>): List<SubtitleOption> =
        captions.map {
            val isFile = it.source == CaptionSource.SIDECAR || it.source == CaptionSource.PICKED
            SubtitleOption(
                url = it.url,
                language = it.languageTag,
                label =
                    if (isFile) {
                        localizedLanguageName(it.languageTag) ?: it.label?.substringAfterLast('/') ?: captionLabel(it)
                    } else {
                        captionLabel(it)
                    },
                detail = it.label.takeIf { isFile },
                trackId = it.trackId,
                isLabelFromSource = !isFile && it.label.isNullOrBlank() && !it.name.isNullOrBlank(),
                isAutoGenerated = it.isAutoGenerated,
                isTranslated = it.isTranslated,
                origin =
                    when (it.source) {
                        CaptionSource.SIDECAR, CaptionSource.PICKED -> SubtitleOrigin.FILE
                        else -> SubtitleOrigin.ONLINE
                    },
            )
        }

    private fun captionLabel(caption: ResolvedCaption): String =
        caption.label?.takeIf { it.isNotBlank() }
            ?: caption.name?.takeIf { it.isNotBlank() }
            ?: localizedLanguageName(caption.languageTag)
            ?: caption.languageTag.ifBlank { UNKNOWN_LANGUAGE }

    internal fun localizedLanguageName(languageTag: String): String? {
        val languageLocale = Locale.forLanguageTag(languageTag.replace('_', '-'))
        val languageCode = languageLocale.language.takeIf { it.isNotBlank() } ?: return null
        val displayLocale = Locale.getDefault()
        val displayName = languageLocale.getDisplayLanguage(displayLocale)
        if (displayName.isBlank() || displayName.equals(languageCode, ignoreCase = true)) return null
        return displayName.replaceFirstChar { character ->
            if (character.isLowerCase()) character.titlecase(displayLocale) else character.toString()
        }
    }

    internal fun audioTrackLanguageTag(trackId: String): String? {
        val normalized = trackId.trim()
        if (normalized.isEmpty()) return null

        val withoutRoleSuffix = normalized.substringBeforeLast('.', missingDelimiterValue = "")
        if (withoutRoleSuffix.isNotBlank()) return withoutRoleSuffix

        if (normalized.startsWith("A_")) {
            return normalized.substringAfterLast('_').takeIf { it.isNotBlank() }
        }

        return normalized.replace('_', '-').takeIf {
            Locale.forLanguageTag(it.replace('_', '-')).language.isNotBlank()
        }
    }

    internal fun audioTrackGroupingKey(
        trackId: String?,
        trackName: String?,
        languageTag: String?,
        trackType: String?,
    ): String {
        val type = trackType.orEmpty().lowercase(Locale.ROOT)
        trackId
            ?.trim()
            ?.takeIf { it.isNotEmpty() }
            ?.let { return "id:${it.lowercase(Locale.ROOT)}" }
        trackName
            ?.trim()
            ?.takeIf { it.isNotEmpty() }
            ?.let { return "name:${it.lowercase(Locale.ROOT)}|$type" }
        languageTag
            ?.trim()
            ?.takeIf { it.isNotEmpty() }
            ?.let { return "language:${it.lowercase(Locale.ROOT)}|$type" }
        return UNTAGGED_TRACK_KEY
    }
}
